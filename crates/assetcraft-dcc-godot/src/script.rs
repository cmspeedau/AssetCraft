//! Godot-side script and scene generation.

use std::path::{Path, PathBuf};

use assetcraft_dcc_blender::plan::ExportPlan;

use crate::material::{orm_pack, GodotMaterial};

pub const SCRIPT_NAME: &str = "assetcraft_export.gd";
pub const SCENE_NAME: &str = "assetcraft_export.tscn";

fn res_path(target: &Path) -> String {
    format!("res://{}", target.to_string_lossy().replace('\\', "/"))
}

fn sanitize(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() || out.chars().next().unwrap().is_ascii_digit() {
        out.insert(0, '_');
    }
    out
}

pub fn materials(plan: &ExportPlan, export_dir: &Path) -> Vec<GodotMaterial> {
    plan.materials
        .iter()
        .map(|spec| {
            let mut gm = GodotMaterial::from_material_spec(spec);
            if gm.can_be_orm() {
                match orm_pack(
                    export_dir,
                    &gm.name,
                    gm.ambient_occlusion.as_deref(),
                    gm.roughness.as_deref(),
                    gm.metallic.as_deref(),
                ) {
                    Ok(packed) => gm.orm = packed,
                    Err(_) => gm.orm = None,
                }
            }
            gm
        })
        .collect()
}

pub fn material_script(plan: &ExportPlan, import_meshes: bool) -> String {
    let mats = materials(plan, &plan.dir());
    let mut out = String::new();
    out.push_str("# Generated by AssetCraft. Do not edit by hand.\n");
    out.push_str("extends Node3D\n\n");

    for m in &mats {
        out.push_str(&format!(
            "func _build_{}() -> Material:\n",
            sanitize(&m.name)
        ));
        if m.orm.is_some() {
            out.push_str("    var m = ORMMaterial3D.new()\n");
            if let Some(p) = &m.orm {
                out.push_str(&format!(
                    "    m.orm_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            }
        } else {
            out.push_str("    var m = StandardMaterial3D.new()\n");
            if let Some(p) = &m.albedo {
                out.push_str(&format!(
                    "    m.albedo_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            }
            if let Some(p) = &m.metallic {
                out.push_str(&format!(
                    "    m.metallic = 0.0\n    m.metallic_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            } else {
                out.push_str("    m.metallic = 0.0\n");
            }
            if let Some(p) = &m.roughness {
                out.push_str(&format!(
                    "    m.roughness = 1.0\n    m.roughness_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            } else {
                out.push_str("    m.roughness = 0.5\n");
            }
            if let Some(p) = &m.normal {
                out.push_str(&format!(
                    "    m.normal_enabled = true\n    m.normal_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            }
            if let Some(p) = &m.emission {
                out.push_str(&format!(
                    "    m.emission_enabled = true\n    m.emission_texture = _load_tex(\"{}\")\n",
                    res_path(p)
                ));
            }
            if let Some(p) = &m.ambient_occlusion {
                out.push_str(&format!(
                    "    # ambient occlusion map (no ORM packing): {}\n",
                    res_path(p)
                ));
            }
        }
        out.push_str("    return m\n\n");
    }

    out.push_str("func _load_tex(path: String) -> Texture2D:\n");
    out.push_str("    if path == \"\":\n        return null\n");
    out.push_str("    var img = Image.load_from_file(ProjectSettings.globalize_path(path))\n");
    out.push_str("    if img == null:\n        return null\n");
    out.push_str("    var tex = ImageTexture.create_from_image(img)\n");
    out.push_str("    return tex\n\n");

    out.push_str("func _ready() -> void:\n");
    for m in &mats {
        out.push_str(&format!(
            "    var mat_{} = _build_{}()\n",
            sanitize(&m.name),
            sanitize(&m.name)
        ));
    }
    if import_meshes {
        out.push_str("    # Meshes are instanced by the scene file; materials are\n");
        out.push_str("    # assigned to every MeshInstance3D whose name contains the\n");
        out.push_str("    # material name (case-insensitive).\n");
        for m in &mats {
            out.push_str(&format!(
                "    _apply_material(\"{}\", mat_{})\n",
                m.name,
                sanitize(&m.name)
            ));
        }
    }
    out.push('\n');

    out.push_str("func _apply_material(material_name: String, mat: Material) -> void:\n");
    out.push_str("    for child in get_children():\n");
    out.push_str("        if child is MeshInstance3D:\n");
    out.push_str("            if child.name.to_lower().contains(material_name.to_lower()):\n");
    out.push_str("                child.set_surface_override_material(0, mat)\n");
    out.push_str("        _apply_recursive(child, material_name, mat)\n");
    out.push('\n');
    out.push_str(
        "func _apply_recursive(node: Node, material_name: String, mat: Material) -> void:\n",
    );
    out.push_str("    for child in node.get_children():\n");
    out.push_str("        if child is MeshInstance3D:\n");
    out.push_str("            if child.name.to_lower().contains(material_name.to_lower()):\n");
    out.push_str("                child.set_surface_override_material(0, mat)\n");
    out.push_str("        _apply_recursive(child, material_name, mat)\n");

    out
}

pub fn scene(plan: &ExportPlan) -> String {
    scene_with_meshes(&preferred_meshes(plan))
}

/// Generate the scene while instancing only meshes that the project has
/// imported. When called before Godot's first import scan, unresolved resource
/// paths stay out of the scene rather than creating invalid ext resources.
pub fn scene_with_meshes(meshes: &[PathBuf]) -> String {
    let mut out = String::new();
    // Godot counts each external resource plus the scene itself in load_steps.
    out.push_str(&format!(
        "[gd_scene load_steps={} format=3]\n\n",
        meshes.len() + 2
    ));
    let mut idx = 1;
    let mut mesh_ids = Vec::new();
    for mesh in meshes {
        out.push_str(&format!(
            "[ext_resource type=\"PackedScene\" path=\"{}\" id=\"{}\"]\n",
            res_path(mesh),
            idx
        ));
        mesh_ids.push(idx);
        idx += 1;
    }
    out.push_str(&format!(
        "[ext_resource type=\"Script\" path=\"res://{}\" id=\"{}\"]\n\n",
        SCENE_NAME.replace(".tscn", ".gd"),
        idx
    ));
    let script_id = idx;

    out.push_str("[node name=\"AssetCraftExport\" type=\"Node3D\"]\n");
    out.push_str(&format!("script = ExtResource(\"{}\")\n\n", script_id));

    for (i, mesh) in meshes.iter().enumerate() {
        let name = mesh
            .file_stem()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_else(|| format!("mesh_{i}"));
        out.push_str(&format!(
            "[node name=\"{}\" parent=\".\" instance=ExtResource(\"{}\")]\n",
            name, mesh_ids[i]
        ));
    }
    out
}

pub fn preferred_meshes(plan: &ExportPlan) -> Vec<PathBuf> {
    let gltf: Vec<PathBuf> = plan
        .meshes
        .iter()
        .filter(|m| {
            m.extension()
                .and_then(|e| e.to_str())
                .map(|e| e.eq_ignore_ascii_case("glb") || e.eq_ignore_ascii_case("gltf"))
                .unwrap_or(false)
        })
        .cloned()
        .collect();
    if gltf.is_empty() {
        plan.meshes.clone()
    } else {
        gltf
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use assetcraft_core::AssetId;
    use assetcraft_dcc_blender::plan;
    use std::path::PathBuf;

    fn plan_from(names: &[&str]) -> ExportPlan {
        let files: Vec<PathBuf> = names.iter().map(PathBuf::from).collect();
        plan("/lib", &AssetId::new("rock-1"), "fbx", &files)
    }

    #[test]
    fn material_script_builds_standard_material_when_no_orm() {
        let plan = plan_from(&["rock_basecolor.png", "rock_normal.png"]);
        let script = material_script(&plan, true);
        assert!(script.contains("StandardMaterial3D.new()"));
        assert!(script.contains("rock_basecolor.png"));
        assert!(script.contains("rock_normal.png"));
    }

    #[test]
    fn scene_references_meshes_and_script() {
        let plan = plan_from(&["SM_Rock.fbx", "rock_basecolor.png"]);
        let scene = scene(&plan);
        assert!(scene.contains("[gd_scene"));
        assert!(scene.contains("assetcraft_export.gd"));
        assert!(scene.contains("SM_Rock"));
    }

    #[test]
    fn preferred_meshes_prefers_gltf() {
        let plan = plan_from(&["SM_Rock.glb", "SM_Rock.fbx", "rock_basecolor.png"]);
        let meshes = preferred_meshes(&plan);
        assert_eq!(meshes, vec![PathBuf::from("meshes/SM_Rock.glb")]);
    }

    #[test]
    fn preferred_meshes_falls_back_to_all() {
        let plan = plan_from(&["SM_Rock.fbx", "rock_basecolor.png"]);
        let meshes = preferred_meshes(&plan);
        assert_eq!(meshes, vec![PathBuf::from("meshes/SM_Rock.fbx")]);
    }

    #[test]
    fn sanitize_produces_valid_identifiers() {
        assert_eq!(sanitize("rock"), "rock");
        assert_eq!(sanitize("1rock"), "_1rock");
        assert_eq!(sanitize("a-b"), "a_b");
    }
}

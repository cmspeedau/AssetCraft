#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    use assetcraft_core::AssetId;

    fn plan() -> ExportPlan {
        crate::plan(
            "/lib",
            &AssetId::new("rock-1"),
            "fbx",
            &[
                PathBuf::from("rock_basecolor.png"),
                PathBuf::from("rock_normal.png"),
                PathBuf::from("rock_glossiness.png"),
                PathBuf::from("rock.fbx"),
            ],
        )
    }

    #[test]
    fn embeds_the_meshes_and_materials_as_python_data() {
        let script = material_script(&plan(), true);
        assert!(script.contains("ASSET = \"rock-1\""));
        assert!(script.contains("IMPORT_MESHES = True"));
        assert!(script.contains("\"/lib/rock-1/fbx/meshes/rock.fbx\""));
        assert!(script.contains("(\"rock\", ["));
        assert!(script.contains("(\"BaseColor\", \"/lib/rock-1/fbx/textures/rock_basecolor.png\")"));
        assert!(script
            .contains("(\"InvertedRoughness\", \"/lib/rock-1/fbx/textures/rock_glossiness.png\")"));
    }

    #[test]
    fn mesh_import_can_be_turned_off() {
        let script = material_script(&plan(), false);
        assert!(script.contains("IMPORT_MESHES = False"));
    }

    #[test]
    fn glossiness_is_wired_through_an_invert() {
        let script = material_script(&plan(), true);
        assert!(script.contains("invert.operation = 'SUBTRACT'"));
    }

    #[test]
    fn socket_names_are_looked_up_across_blender_versions() {
        let script = material_script(&plan(), true);
        // The renamed sockets appear as fallbacks, not as the only name.
        assert!(script.contains("'Specular IOR Level', 'Specular'"));
        assert!(script.contains("'Emission Color', 'Emission'"));
        assert!(script.contains("bpy.ops.wm.obj_import"));
        assert!(script.contains("bpy.ops.import_scene.obj"));
    }

    #[test]
    fn paths_are_escaped_rather_than_embedded_raw() {
        // A Windows path must survive as an escaped literal, not a raw string
        // (a raw string would break on a trailing backslash).
        assert_eq!(
            py_str("C:\\assets\\rock.png"),
            "\"C:\\\\assets\\\\rock.png\""
        );
        assert_eq!(py_str("a\"b"), "\"a\\\"b\"");
        assert_eq!(py_str("plain"), "\"plain\"");
    }
}
